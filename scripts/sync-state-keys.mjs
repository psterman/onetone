// Generate channel-config-state-keys.generated.js from shape; --check fails if stale.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CHANNEL_CONFIG_STATE_SHAPE } from './channel-config-state-shape.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = join(root, 'src/js/features/settings/channel-config-state-keys.generated.js');
const check = process.argv.includes('--check');

const keys = [...new Set(CHANNEL_CONFIG_STATE_SHAPE)].sort();
const body = `// AUTO-GENERATED by scripts/sync-state-keys.mjs — do not edit
(function (g) {
  g.__CHANNEL_CONFIG_GENERATED_KEYS__ = ${JSON.stringify(keys, null, 2)};
})(typeof window !== 'undefined' ? window : globalThis);
`;

if (check) {
  if (!existsSync(outPath)) {
    console.error('[sync-state-keys] missing generated file; run: npm run sync:state-keys');
    process.exit(1);
  }
  const cur = readFileSync(outPath, 'utf8');
  if (cur !== body) {
    console.error('[sync-state-keys] generated file stale; run: npm run sync:state-keys');
    process.exit(1);
  }
  console.log('[sync-state-keys] OK (fresh)');
} else {
  writeFileSync(outPath, body, 'utf8');
  console.log('[sync-state-keys] wrote', outPath, '(' + keys.length + ' keys)');
}
